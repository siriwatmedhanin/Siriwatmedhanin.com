/* ---------- Apply translations ---------- */
function applyLanguage(lang) {
  const t = translations[lang];
  if (!t) return;

  // Update all [data-i18n] elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // Update <html lang> attribute
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

  // Update lang buttons active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('lang-btn--active', btn.dataset.lang === lang);
  });

  // Persist to localStorage
  localStorage.setItem('smg-lang', lang);

  // Dispatch languageChanged event for subpages
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang, translations: t } }));
}

/* ---------- Init ---------- */
function initI18n() {
  // Wire up buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => applyLanguage(btn.dataset.lang));
  });

  // Restore saved language (default TH)
  const saved = localStorage.getItem('smg-lang') || 'th';
  if (saved !== 'th') {
    applyLanguage(saved);
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
